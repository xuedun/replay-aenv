#!/usr/bin/env python3
"""Plot mean trajectory completion time by oversubscription ratio.

The input is trajectory-detail.csv produced by
run_pause_resume_oversubscription_benchmark.py.  Each CSV row is treated as one
trajectory execution.  The overall mean is therefore weighted by the number of
executions, while per-trajectory means are grouped by source_trajectory.
"""

from __future__ import annotations

import argparse
import csv
import math
import re
import statistics
import sys
import textwrap
from collections import defaultdict
from pathlib import Path
from typing import Any, Iterable

import matplotlib

matplotlib.use("Agg")
from matplotlib import pyplot as plt  # noqa: E402


REQUIRED_COLUMNS = {
    "ratio",
    "repeat",
    "oversubscription_ratio",
    "task_index",
    "source_trajectory",
    "elapsed_sec",
    "replay_completed",
    "succeeded",
}

SUMMARY_COLUMNS = [
    "plot_type",
    "trajectory_index",
    "trajectory",
    "ratio",
    "oversubscription_ratio",
    "count",
    "mean_sec",
    "min_sec",
    "max_sec",
    "std_sec",
]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Plot overall and per-source-trajectory mean completion time for "
            "each oversubscription ratio."
        )
    )
    parser.add_argument(
        "trajectory_detail_csv",
        type=Path,
        help="trajectory-detail.csv generated by the oversubscription benchmark",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        help=(
            "output directory (default: <CSV directory>/trajectory-completion-plots)"
        ),
    )
    parser.add_argument(
        "--success-only",
        action="store_true",
        help="also require succeeded=True; incomplete rows are always excluded",
    )
    parser.add_argument(
        "--dpi",
        type=int,
        default=180,
        help="PNG resolution in dots per inch (default: 180)",
    )
    args = parser.parse_args()
    if args.dpi <= 0:
        parser.error("--dpi must be positive")
    return args


def parse_bool(value: str) -> bool:
    return value.strip().lower() in {"1", "true", "yes", "y"}


def natural_key(value: str) -> list[tuple[int, int | str]]:
    parts = re.split(r"(\d+)", value.casefold())
    return [(0, int(part)) if part.isdigit() else (1, part) for part in parts]


def safe_filename(value: str, max_length: int = 150) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9._-]+", "-", value).strip("-._")
    return (cleaned or "trajectory")[:max_length]


def stats(values: list[float]) -> dict[str, float | int]:
    return {
        "count": len(values),
        "mean_sec": statistics.fmean(values),
        "min_sec": min(values),
        "max_sec": max(values),
        "std_sec": statistics.pstdev(values),
    }


def load_records(
    csv_path: Path, *, success_only: bool
) -> tuple[list[dict[str, Any]], dict[str, int]]:
    counters = {
        "total": 0,
        "included": 0,
        "incomplete": 0,
        "unsuccessful": 0,
        "invalid_elapsed": 0,
    }
    records: list[dict[str, Any]] = []
    seen_execution_keys: set[tuple[str, str, str]] = set()

    with csv_path.open("r", encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames is None:
            raise ValueError(f"CSV has no header: {csv_path}")
        missing = sorted(REQUIRED_COLUMNS - set(reader.fieldnames))
        if missing:
            raise ValueError("CSV is missing required columns: " + ", ".join(missing))

        for line_number, row in enumerate(reader, start=2):
            counters["total"] += 1
            execution_key = (
                row["ratio"].strip(),
                row["repeat"].strip(),
                row["task_index"].strip(),
            )
            if execution_key in seen_execution_keys:
                raise ValueError(
                    f"duplicate execution key at line {line_number}: "
                    f"ratio={execution_key[0]}, repeat={execution_key[1]}, "
                    f"task_index={execution_key[2]}"
                )
            seen_execution_keys.add(execution_key)

            if not parse_bool(row["replay_completed"]):
                counters["incomplete"] += 1
                continue
            if success_only and not parse_bool(row["succeeded"]):
                counters["unsuccessful"] += 1
                continue

            try:
                elapsed_sec = float(row["elapsed_sec"])
            except (TypeError, ValueError):
                counters["invalid_elapsed"] += 1
                continue
            if not math.isfinite(elapsed_sec) or elapsed_sec < 0:
                counters["invalid_elapsed"] += 1
                continue

            ratio = row["ratio"].strip()
            ratio_label = row["oversubscription_ratio"].strip()
            trajectory = row["source_trajectory"].strip()
            if not ratio or not ratio_label or not trajectory:
                raise ValueError(
                    f"line {line_number} has an empty ratio, ratio label, or source trajectory"
                )
            try:
                ratio_sort = float(ratio)
            except ValueError as exc:
                raise ValueError(
                    f"line {line_number} has a non-numeric ratio: {ratio!r}"
                ) from exc
            if not math.isfinite(ratio_sort):
                raise ValueError(f"line {line_number} has a non-finite ratio: {ratio!r}")

            records.append(
                {
                    "ratio": ratio,
                    "ratio_sort": ratio_sort,
                    "ratio_label": ratio_label,
                    "trajectory": trajectory,
                    "elapsed_sec": elapsed_sec,
                }
            )
            counters["included"] += 1

    if not records:
        raise ValueError("no valid completed trajectory executions remain after filtering")
    return records, counters


def group_records(
    records: Iterable[dict[str, Any]],
) -> tuple[
    list[str],
    dict[str, dict[str, str | float]],
    dict[str, list[float]],
    dict[str, dict[str, list[float]]],
]:
    ratio_metadata: dict[str, dict[str, str | float]] = {}
    overall: dict[str, list[float]] = defaultdict(list)
    per_trajectory: dict[str, dict[str, list[float]]] = defaultdict(
        lambda: defaultdict(list)
    )

    for record in records:
        ratio = str(record["ratio"])
        metadata = {
            "ratio_sort": float(record["ratio_sort"]),
            "ratio_label": str(record["ratio_label"]),
        }
        previous = ratio_metadata.get(ratio)
        if previous is not None and previous != metadata:
            raise ValueError(
                f"ratio {ratio!r} has inconsistent oversubscription labels or sort values"
            )
        ratio_metadata[ratio] = metadata
        elapsed_sec = float(record["elapsed_sec"])
        trajectory = str(record["trajectory"])
        overall[ratio].append(elapsed_sec)
        per_trajectory[trajectory][ratio].append(elapsed_sec)

    ratios = sorted(
        ratio_metadata,
        key=lambda value: (float(ratio_metadata[value]["ratio_sort"]), value),
    )
    return ratios, ratio_metadata, overall, per_trajectory


def validate_weighting(
    ratios: Iterable[str],
    overall: dict[str, list[float]],
    per_trajectory: dict[str, dict[str, list[float]]],
) -> None:
    for ratio in ratios:
        total_count = sum(
            len(ratio_values.get(ratio, []))
            for ratio_values in per_trajectory.values()
        )
        if total_count != len(overall[ratio]):
            raise AssertionError(
                f"sample-count mismatch for ratio {ratio}: "
                f"overall={len(overall[ratio])}, per-trajectory={total_count}"
            )
        weighted_sum = sum(
            sum(ratio_values.get(ratio, []))
            for ratio_values in per_trajectory.values()
        )
        if not math.isclose(
            weighted_sum / total_count,
            statistics.fmean(overall[ratio]),
            rel_tol=1e-12,
            abs_tol=1e-9,
        ):
            raise AssertionError(f"weighted-mean mismatch for ratio {ratio}")


def plot_means(
    output_path: Path,
    *,
    title: str,
    ratios: list[str],
    ratio_metadata: dict[str, dict[str, str | float]],
    values_by_ratio: dict[str, list[float]],
    dpi: int,
) -> None:
    figure, axis = plt.subplots(figsize=(9.5, 5.5))
    positions = list(range(len(ratios)))
    means = [
        statistics.fmean(values_by_ratio[ratio])
        if values_by_ratio.get(ratio)
        else math.nan
        for ratio in ratios
    ]
    axis.plot(positions, means, color="#2563eb", marker="o", linewidth=2.0)

    for position, ratio, mean_sec in zip(positions, ratios, means):
        values = values_by_ratio.get(ratio, [])
        if not values:
            continue
        axis.annotate(
            f"{mean_sec:.2f}s",
            (position, mean_sec),
            xytext=(0, 9),
            textcoords="offset points",
            ha="center",
            va="bottom",
            fontsize=8,
        )

    axis.set_xticks(
        positions,
        [str(ratio_metadata[ratio]["ratio_label"]) for ratio in ratios],
    )
    axis.set_xlabel("Oversubscription ratio")
    axis.set_ylabel("Mean completion time (s)")
    axis.set_title(title, fontsize=13, pad=12)
    finite_means = [value for value in means if math.isfinite(value)]
    minimum_mean = min(finite_means)
    maximum_mean = max(finite_means)
    mean_range = maximum_mean - minimum_mean
    if mean_range > 0:
        lower_padding = max(mean_range * 0.18, maximum_mean * 0.01, 0.5)
        upper_padding = max(mean_range * 0.30, maximum_mean * 0.02, 1.0)
    else:
        lower_padding = max(abs(maximum_mean) * 0.05, 1.0)
        upper_padding = lower_padding
    axis.set_ylim(
        bottom=max(0.0, minimum_mean - lower_padding),
        top=maximum_mean + upper_padding,
    )
    axis.grid(axis="both", linestyle="--", alpha=0.35)
    figure.tight_layout()
    figure.savefig(output_path, dpi=dpi, bbox_inches="tight")
    plt.close(figure)


def summary_row(
    *,
    plot_type: str,
    trajectory_index: str,
    trajectory: str,
    ratio: str,
    ratio_label: str,
    values: list[float],
) -> dict[str, Any]:
    values_stats = stats(values)
    return {
        "plot_type": plot_type,
        "trajectory_index": trajectory_index,
        "trajectory": trajectory,
        "ratio": ratio,
        "oversubscription_ratio": ratio_label,
        "count": values_stats["count"],
        "mean_sec": f"{float(values_stats['mean_sec']):.9f}",
        "min_sec": f"{float(values_stats['min_sec']):.9f}",
        "max_sec": f"{float(values_stats['max_sec']):.9f}",
        "std_sec": f"{float(values_stats['std_sec']):.9f}",
    }


def write_summary(path: Path, rows: Iterable[dict[str, Any]]) -> None:
    with path.open("w", encoding="utf-8-sig", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=SUMMARY_COLUMNS)
        writer.writeheader()
        writer.writerows(rows)


def main() -> int:
    args = parse_args()
    csv_path = args.trajectory_detail_csv.expanduser().resolve()
    if not csv_path.is_file():
        print(f"error: input CSV does not exist: {csv_path}", file=sys.stderr)
        return 2
    output_dir = (
        args.output_dir.expanduser().resolve()
        if args.output_dir
        else csv_path.parent / "trajectory-completion-plots"
    )

    try:
        records, counters = load_records(csv_path, success_only=args.success_only)
        ratios, ratio_metadata, overall, per_trajectory = group_records(records)
        validate_weighting(ratios, overall, per_trajectory)
    except (OSError, ValueError, AssertionError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    output_dir.mkdir(parents=True, exist_ok=True)
    summary_rows: list[dict[str, Any]] = []
    produced: list[Path] = []

    overall_path = output_dir / "trajectory-duration-overall.png"
    plot_means(
        overall_path,
        title="Overall mean trajectory completion time",
        ratios=ratios,
        ratio_metadata=ratio_metadata,
        values_by_ratio=overall,
        dpi=args.dpi,
    )
    produced.append(overall_path)
    for ratio in ratios:
        summary_rows.append(
            summary_row(
                plot_type="overall",
                trajectory_index="",
                trajectory="",
                ratio=ratio,
                ratio_label=str(ratio_metadata[ratio]["ratio_label"]),
                values=overall[ratio],
            )
        )

    trajectories = sorted(
        per_trajectory,
        key=lambda value: (natural_key(Path(value).name), value.casefold()),
    )
    for index, trajectory in enumerate(trajectories, start=1):
        trajectory_name = Path(trajectory).name
        plot_path = output_dir / (
            f"trajectory-duration-{index:03d}-"
            f"{safe_filename(Path(trajectory).stem)}.png"
        )
        wrapped_name = textwrap.fill(trajectory_name, width=100)
        plot_means(
            plot_path,
            title=f"Mean completion time\n{wrapped_name}",
            ratios=ratios,
            ratio_metadata=ratio_metadata,
            values_by_ratio=per_trajectory[trajectory],
            dpi=args.dpi,
        )
        produced.append(plot_path)
        for ratio in ratios:
            values = per_trajectory[trajectory].get(ratio, [])
            if not values:
                continue
            summary_rows.append(
                summary_row(
                    plot_type="trajectory",
                    trajectory_index=str(index),
                    trajectory=trajectory,
                    ratio=ratio,
                    ratio_label=str(ratio_metadata[ratio]["ratio_label"]),
                    values=values,
                )
            )

    summary_path = output_dir / "trajectory-duration-summary.csv"
    write_summary(summary_path, summary_rows)

    print(f"Input rows: {counters['total']}")
    print(f"Included executions: {counters['included']}")
    print(f"Excluded incomplete: {counters['incomplete']}")
    if args.success_only:
        print(f"Excluded unsuccessful: {counters['unsuccessful']}")
    print(f"Excluded invalid elapsed_sec: {counters['invalid_elapsed']}")
    print(f"Source trajectories: {len(trajectories)}")
    print(f"Oversubscription ratios: {len(ratios)}")
    print(f"Plots written: {len(produced)}")
    for path in produced:
        print(f"  {path}")
    print(f"Summary written: {summary_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
